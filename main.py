def draw_globe():
    # atmosphere glow
    for r, a in ((GR + 26, 18), (GR + 18, 28), (GR + 10, 45), (GR + 4, 70)):
        ring(GCX, GCY, r - 6, r, (70, 130, 150), a)
    # ocean: per-pixel gradient, gold-lit on the east, midnight west
    for y in range(GCY - GR, GCY + GR + 1):
        dy = y - GCY
        dx = int(math.sqrt(max(0, GR * GR - dy * dy)))
        for x in range(GCX - dx, GCX + dx + 1):
            t = (x - (GCX - GR)) / float(2 * GR)
            r = int(TEAL_D[0] + (TEAL_L[0] - TEAL_D[0]) * t)
            g = int(TEAL_D[1] + (TEAL_L[1] - TEAL_D[1]) * t)
            b = int(TEAL_D[2] + (TEAL_L[2] - TEAL_D[2]) * t)
            set_px(x, y, (r, g, b))
    ring(GCX, GCY, GR - 1, GR, GOLD, 255)
    # land, each continent its own mass
    for coords in (AFRICA, EUROPE, ITALY, GREECE, UK, ASIA, ANATOLIA,
                   ARABIA, INDIA, SE_ASIA_ISLES):
        land_poly(coords, LAND)
    # night shading on the west half (multiply down, clipped to disc)
    for y in range(GCY - GR, GCY + GR + 1):
        dy = y - GCY
        dx = int(math.sqrt(max(0, GR * GR - dy * dy)))

# ---- canvas: flat RGB bytearray ----
px = bytearray(W * H * 3)


def fill(c):
    r, g, b = c
    px[0::3] = bytes([r]) * (W * H)
    px[1::3] = bytes([g]) * (W * H)
    px[2::3] = bytes([b]) * (W * H)


def set_px(x, y, c):
    if 0 <= x < W and 0 <= y < H:
        i = (y * W + x) * 3
        px[i], px[i + 1], px[i + 2] = c


def blend_px(x, y, c, a):
    # a: 0..255 coverage of colour c over what is already there
    if 0 <= x < W and 0 <= y < H and a > 0:
        i = (y * W + x) * 3
        if a >= 255:
            px[i], px[i + 1], px[i + 2] = c
        else:
            px[i] = (c[0] * a + px[i] * (255 - a)) // 255
            px[i + 1] = (c[1] * a + px[i + 1] * (255 - a)) // 255
            px[i + 2] = (c[2] * a + px[i + 2] * (255 - a)) // 255


def rect(x0, y0, x1, y1, c, a=255):
    x0 = max(0, x0)
    y0 = max(0, y0)
    x1 = min(W, x1)
    y1 = min(H, y1)
    if a >= 255:
        for y in range(y0, y1):
            i = (y * W + x0) * 3
            n = x1 - x0
            px[i:i + n * 3:3] = bytes([c[0]]) * n
            px[i + 1:i + n * 3 + 1:3] = bytes([c[1]]) * n
            px[i + 2:i + n * 3 + 2:3] = bytes([c[2]]) * n
    else:
        for y in range(y0, y1):
            for x in range(x0, x1):
                blend_px(x, y, c, a)


def hline(x0, x1, y, c, w=1):
    for yy in range(y, y + w):
        for x in range(x0, x1):
            set_px(x, yy, c)


def vline(x, y0, y1, c, w=1):
    for xx in range(x, x + w):
        for y in range(y0, y1):
            set_px(xx, y, c)


def line(x0, y0, x1, y1, c, w=1):
    dx = x1 - x0
    dy = y1 - y0
    n = max(abs(dx), abs(dy), 1)
    for s in range(n + 1):
        x = x0 + dx * s // n
        y = y0 + dy * s // n
        for ox in range(w):
            for oy in range(w):
                set_px(x + ox - w // 2, y + oy - w // 2, c)


def circle(cx, cy, r, c, a=255):
    for y in range(cy - r, cy + r + 1):
        dy = y - cy
        dx = int(math.sqrt(max(0, r * r - dy * dy)))
        for x in range(cx - dx, cx + dx + 1):
            blend_px(x, y, c, a)


def ring(cx, cy, r0, r1, c, a=255):
    for y in range(cy - r1, cy + r1 + 1):
        dy = y - cy
        for x in range(cx - r1, cx + r1 + 1):
            d2 = (x - cx) ** 2 + dy * dy
            if r0 * r0 <= d2 <= r1 * r1:
                blend_px(x, y, c, a)


def ellipse(cx, cy, rx, ry, c, a=255):
    for y in range(cy - ry, cy + ry + 1):
        dy = (y - cy) / float(ry)
        dx = int(rx * math.sqrt(max(0.0, 1.0 - dy * dy)))
        for x in range(cx - dx, cx + dx + 1):
            blend_px(x, y, c, a)


def poly(points, c, a=255):
    # scanline fill, even-odd
    if len(points) < 3:
        return
    ys = [p[1] for p in points]
    for y in range(max(0, min(ys)), min(H, max(ys) + 1)):
        xs = []
        n = len(points)
        for k in range(n):
            x0, y0 = points[k]
            x1, y1 = points[(k + 1) % n]
            if (y0 <= y < y1) or (y1 <= y < y0):
                xs.append(x0 + (y - y0) * (x1 - x0) / float(y1 - y0))
        xs.sort()
        for k in range(0, len(xs) - 1, 2):
            for x in range(int(math.ceil(xs[k])), int(xs[k + 1]) + 1):
                blend_px(x, y, c, a)


# ---- PNG encoder (stdlib) ----
def write_png(path):
    raw = bytearray()
    for y in range(H):
        raw.append(0)
        raw += px[y * W * 3:(y + 1) * W * 3]
    comp = zlib.compress(bytes(raw), 9)

    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data +
                struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)
    data = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) +
            chunk(b"IDAT", comp) + chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(data)
    return len(data)


# ---- text rendering: 2x supersampled blits of the filled bitmaps ----
# cell_t / tracking_t are in 2x-temp pixels; the final cell is half that,
# so glyph edges land on half pixels and read smooth instead of blocky.
SS = 2


def text_w(font, text, cell_t, tracking_t):
    w = 0
    for ch in text:
        if ch not in font:
            raise KeyError("glyph missing: %r" % ch)
        w += len(font[ch][0]) * cell_t + tracking_t
    return max(0, (w - tracking_t) // SS)


def text_h(font, cell_t):
    return len(next(iter(font.values()))) * cell_t // SS


def draw_text(font, text, x, y, color, cell_t, tracking_t, align="left"):
    # x, y = top-left of the cap box (y is the cap top). align applies to x.
    gw = len(next(iter(font.values()))[0])
    gh = len(next(iter(font.values())))
    tw = 0
    for ch in text:
        if ch not in font:
            raise KeyError("glyph missing: %r" % ch)
        tw += len(font[ch][0]) * cell_t + tracking_t
    tw -= tracking_t
    th = gh * cell_t
    if align == "center":
        x = x - (tw // SS) // 2
    elif align == "right":
        x = x - tw // SS
    # temp coverage buffer at 2x
    tmp = bytearray(tw * th)
    cx = 0
    for ch in text:
        rows = font[ch]
        for ry, row in enumerate(rows):
            for rx, bit in enumerate(row):
                if bit == "#":
                    for ty in range(ry * cell_t, (ry + 1) * cell_t):
                        base = ty * tw + cx + rx * cell_t
                        for tx in range(cell_t):
                            tmp[base + tx] = 1
        cx += len(rows[0]) * cell_t + tracking_t
    # box-downsample 2x2 -> blend
    fw = tw // SS
    fh = th // SS
    for fy in range(fh):
        for fx in range(fw):
            cov = (tmp[(fy * SS) * tw + fx * SS] +
                   tmp[(fy * SS) * tw + fx * SS + 1] +
                   tmp[(fy * SS + 1) * tw + fx * SS] +
                   tmp[(fy * SS + 1) * tw + fx * SS + 1])
            if cov:
                blend_px(x + fx, y + fy, color, cov * 255 // 4)
    return fw


# ---- globe: orthographic Earth, Europe drawn apart from Asia ----
GCX, GCY, GR = 512, 405, 140
LAT0 = math.radians(28.0)
LON0 = math.radians(25.0)
COS0 = math.cos(LAT0)
SIN0 = math.sin(LAT0)


def project(lat_deg, lon_deg):
    lat = math.radians(lat_deg)
    lon = math.radians(lon_deg)
    dlon = lon - LON0
    z = SIN0 * math.sin(lat) + COS0 * math.cos(lat) * math.cos(dlon)
    x = GCX + GR * math.cos(lat) * math.sin(dlon)
    y = GCY - GR * (COS0 * math.sin(lat) - SIN0 * math.cos(lat) * math.cos(dlon))
    return x, y, z


def land_poly(coords, color):
    # coords: list of (lat, lon). Edges are sampled so the limb clips
    # cleanly; only visible runs are filled.
    pts = []
    for k in range(len(coords)):
        a = coords[k]
        b = coords[(k + 1) % len(coords)]
        steps = 24
        for s in range(steps):
            t = s / float(steps)
            lat = a[0] + (b[0] - a[0]) * t
            lon = a[1] + (b[1] - a[1]) * t
            pts.append((lat, lon))
    run = []
    for lat, lon in pts:
        x, y, z = project(lat, lon)
        if z > 0.02:
            run.append((int(x), int(y)))
        else:
            if len(run) >= 3:
                poly(run, color)
            run = []
    if len(run) >= 3:
        poly(run, color)


